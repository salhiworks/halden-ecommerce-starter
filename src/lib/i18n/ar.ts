/**
 * Arabic has six plural forms (zero, one, two, few, many, other), so counts
 * are worded through Intl.PluralRules rather than a singular/plural pair.
 * Digits stay Latin, matching prices and phone numbers.
 */
const rules = new Intl.PluralRules("ar");

type Forms = { zero: string; one: string; two: string; few: string; many: string; other: string };

function count(n: number, forms: Forms): string {
  const form = forms[rules.select(n) as keyof Forms] ?? forms.other;
  return form.replace("{n}", String(n));
}

